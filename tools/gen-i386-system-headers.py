#!/usr/bin/env python3
"""Generate private compiler interfaces that avoid rereading guarded headers."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MIRRORS = {
    'Kernel/I386/PublicCompiler.HH': 'Compiler/I386/SystemCompiler.HH',
    'Kernel/I386/PublicLoader.HH': 'Compiler/I386/SystemLoader.HH',
}
PREFIX = b'//Generated by tools/gen-i386-system-headers.py; full public interface preserved.\n'


def include_guard(path):
    lines = path.read_bytes().splitlines()
    match = re.fullmatch(rb'#ifndef ([A-Z0-9_]+)', lines[0])
    if not match or lines[1] != b'#define '+match[1] or lines[-1] != b'#endif':
        raise ValueError('Expected a complete canonical include guard: '+str(path))
    return match[1]


def generated(source):
    #Operate on bytes: HolyC comments and literals can contain legacy characters.
    def guarded(match):
        name = match[1].decode('ascii').lstrip('/')
        guard = include_guard(ROOT/name)
        target = MIRRORS.get(name, name).encode('ascii')
        return b'#ifndef '+guard+b'\n#include "/'+target+b'"\n#endif'
    original = (ROOT/source).read_bytes()
    include_guard(ROOT/source)
    return PREFIX+re.sub(rb'^#include "([^"]+)"$', guarded, original, flags=re.M)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for source, target in MIRRORS.items():
        path, expected = ROOT/target, generated(source)
        if args.check:
            if not path.is_file() or path.read_bytes() != expected:
                stale.append(target)
        else:
            path.write_bytes(expected)
    if stale:
        parser.error('Regenerate private compiler interfaces: '+', '.join(stale))
    print('PASS: two complete compiler interfaces; guarded dependency reads')


if __name__ == '__main__':
    main()
