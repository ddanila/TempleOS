#!/usr/bin/env python3
"""Reproduce the native HolyC DVD stage1 byte array from audited 386 assembly."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile
ROOT=Path(__file__).resolve().parents[1]
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    source=ROOT/'tools/i386-dvd-stage.asm';target=ROOT/'Kernel/I386/DVDStageBytes.HC'
    with tempfile.TemporaryDirectory(prefix='i386-dvd-stage-') as tmp:
        binary=Path(tmp)/'stage.bin';subprocess.run(['nasm','-f','bin',str(source),'-o',str(binary)],check=True);data=binary.read_bytes()
    assert len(data)==2048 and data[16:20]==b'I3CD'
    text='//Generated by tools/build-i386-dvd-loader.py; do not edit bytes.\n'
    text+='//Assembly SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest()+'\n'
    text+='U8 i386_dvd_stage1[2048]={\n'
    text+='\n'.join('  '+','.join(f'0x{v:02X}' for v in data[i:i+16])+(',' if i+16<len(data) else '') for i in range(0,len(data),16))+'\n};\n'
    text+='#define BDVD_START i386_dvd_stage1\n#define BDVD_END (i386_dvd_stage1+2048)\n#define BDVD_BLK_LO (i386_dvd_stage1+20)\n#define BDVD_BLK_CNT (i386_dvd_stage1+24)\n#define BDVD_SHIFT_BLKS (i386_dvd_stage1+26)\n'
    if args.check:
        if not target.is_file() or target.read_text()!=text:raise ValueError('DVD stage bytes need regeneration')
        print('PASS: generated stage1 bytes match assembly')
    else:target.write_text(text)
if __name__=='__main__':main()
