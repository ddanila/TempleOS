#!/usr/bin/env python3
"""Generate the complete private optimizer helper source without nested documents."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated():
    body = (ROOT/'Compiler/I386/PublicOptSupport.HC').read_bytes()
    first = b'#define OPT_PASS012_IMPL NativeSystemOptPass012\n'
    last = b'#define OPT_PASS012_IMPL OptPass012\n'
    marker = b'PUBLIC OPT loaded\\n'
    if body.count(first) != 1 or body.count(last) != 1 or body.count(marker) != 1:
        raise ValueError('Review the canonical optimizer support source')
    body = body.replace(first, b'#include "/Compiler/I386/ResidentOptCore.HC"\n#define OPT_PASS012_CORE_EXTERNAL 1\n'+first)
    body = body.replace(last, last+b'#define OPT_PASS012_CORE_EXTERNAL 0\n')
    body = body.replace(marker, b'PUBLIC OPT resident\\n')
    return b'//Generated by tools/gen-i386-resident-optimizer.py; complete helpers preserved.\n'+body


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT/'Compiler/I386/ResidentOptSupport.HC'
    expected = generated()
    if args.check:
        if not target.is_file() or target.read_bytes() != expected:
            parser.error('Regenerate the private resident optimizer support source')
    else:
        target.write_bytes(expected)
    print('PASS: complete optimizer helpers; resident core; one support document')


if __name__ == '__main__':
    main()
